import { test, expect } from '@playwright/test';
const url='/learn/n5/module-03/chapter-03/lesson-07/';
test('draft persistence, comparison, keyboard, feedback and retry',async({page})=>{
 await page.goto(url);
 await expect(page.getByRole('heading',{name:/Write Yesterday and Tomorrow/})).toBeVisible();
 const draft=page.getByLabel(/Your fictional two-day message/);
 await draft.fill('昨日、本を読みました。明日、勉強します。');
 await page.getByRole('button',{name:'Save draft locally'}).click();
 await draft.fill('');
 await page.getByRole('button',{name:'Load saved draft'}).click();
 await expect(draft).toHaveValue('昨日、本を読みました。明日、勉強します。');
 await page.getByRole('button',{name:'Show comparison model'}).click();
 await expect(page.getByText(/Comparison model — not an automatic writing grade/)).toBeVisible();
 const questions=page.locator('[data-question-id]');
 await expect(questions).toHaveCount(8);
 await questions.first().locator('input[type=radio]').first().focus();
 await page.keyboard.press('Space');
 await expect(questions.first().locator('input[type=radio]').first()).toBeChecked();
 for(let i=1;i<8;i++) await questions.nth(i).locator('input[type=radio]').first().check();
 await page.getByRole('button',{name:'Check all 8 answers'}).click();
 await expect(page.getByText(/Recognition score:/)).toBeVisible();
 await expect(questions.first().getByRole('status')).toBeVisible();
 await page.getByRole('button',{name:'Retry questions'}).click();
 await expect(page.getByRole('button',{name:'Check all 8 answers'})).toBeDisabled();
 await page.getByRole('button',{name:'Clear draft'}).click();
 await expect(draft).toHaveValue('');
});
test('320px dark mode retains keyboard-accessible editor without horizontal overflow',async({page})=>{
 await page.setViewportSize({width:320,height:740});
 await page.emulateMedia({colorScheme:'dark'});
 await page.goto(url);
 await expect(page.getByLabel(/Your fictional two-day message/)).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth)).toBe(false);
});