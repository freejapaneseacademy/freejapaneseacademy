import { test, expect } from '@playwright/test';
test('evidence reading lesson is accessible, scores and fits a 320px viewport', async ({page})=>{
 await page.setViewportSize({width:320,height:700});
 await page.goto('/learn/start/module-03/chapter-04/lesson-05/');
 await expect(page.locator('.page-hero h1')).toContainText('Read a new hiragana library dialogue');
 await expect(page.getByRole('heading',{name:'Check your reading evidence'})).toBeVisible();
 const groups=page.locator('fieldset');
 await expect(groups).toHaveCount(8);
 const submit=page.getByRole('button',{name:'Check all eight answers'});
 await expect(submit).toBeDisabled();
 await expect(page.getByText('Evidence:',{exact:false})).toHaveCount(0);
 for(let i=0;i<8;i++)await groups.nth(i).locator('input[type="radio"]').first().check();
 await expect(submit).toBeEnabled();
 await submit.click();
 await expect(page.getByText(/Reading score: \d\/8/)).toBeVisible();
 await expect(groups.first().getByText('Evidence:',{exact:false})).toBeVisible();
 await page.getByRole('button',{name:'Try the questions again'}).click();
 await expect(submit).toBeDisabled();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth)).toBe(false);
});
