import { test, expect } from '@playwright/test';
const url='/learn/start/module-01/chapter-02/lesson-04/';
test('Chapter 02 L04 kana cards, written check and progress persistence',async({page})=>{
  await page.goto(url);
  await expect(page.getByRole('heading',{level:1,name:/Recognize and type Japanese sound symbols/})).toBeVisible();
  const practice=page.locator('.sound-script-practice');
  await practice.getByRole('button',{name:'Reveal kana'}).click();
  await expect(practice.locator('.script-pair__glyph')).toHaveText('か');
  await practice.getByRole('button',{name:'Next',exact:true}).click();
  await practice.getByRole('button',{name:'Reveal kana'}).click();
  await expect(practice.locator('.script-pair__glyph')).toHaveText('き');
  await practice.getByRole('button',{name:'Clear drawing'}).click();
  const correct=['a','shi','ke','e-kata','umbrella','no','grandma','one-mora'];
  for(let i=0;i<8;i++)await practice.locator('fieldset').nth(i).locator('input[value="'+correct[i]+'"]').check();
  const typed=['か','き','す','かさ'];
  for(let i=0;i<4;i++)await practice.locator('fieldset').nth(i+8).locator('input[type="text"]').fill(typed[i]);
  await practice.getByRole('button',{name:'Check answers & save score'}).click();
  await expect(practice.getByRole('heading',{name:'12 / 12 correct'})).toBeVisible();
  await page.goto('/dashboard/');
  await expect(page.getByText('Foundations: Sound-symbol recognition and typing')).toBeVisible();
  await page.goto(url);
  await page.getByRole('button',{name:/Mark lesson complete/}).click();
  await expect(page.getByRole('button',{name:/Lesson completed/})).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button',{name:/Lesson completed/})).toBeVisible();
});
test('Chapter 02 L04 palette, retry and ungraded writing work without IME',async({page})=>{
  await page.goto(url);
  const practice=page.locator('.sound-script-practice');
  const q=practice.locator('[data-question-id="ex-l0-m01-c02-l04-012"]');
  await q.getByRole('button',{name:'Enter か'}).click();
  await q.getByRole('button',{name:'Enter さ'}).click();
  await expect(q.locator('input[type="text"]')).toHaveValue('かさ');
  await q.getByRole('button',{name:'Delete last'}).click();
  await expect(q.locator('input[type="text"]')).toHaveValue('か');
  await q.getByRole('button',{name:'Clear answer'}).click();
  await expect(q.locator('input[type="text"]')).toHaveValue('');
  await practice.locator('#sound-script-draft').fill('かさ is umbrella; いいえ is no.');
  await practice.getByRole('button',{name:'Compare with model and checklist'}).click();
  await expect(practice.getByText('Model and self-review')).toBeVisible();
});
for(const width of [320,375,390,768,1024,1440])test('Chapter 02 L04 responsive, dark theme and keyboard controls '+width+'px',async({page})=>{
  await page.setViewportSize({width,height:820});
  await page.goto(url);
  const root=page.locator('.sound-script-practice');
  await expect(root).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width+2);
  await page.locator('html').evaluate(el=>{el.dataset.theme='dark';});
  await expect(root.getByRole('button',{name:'Reveal kana'})).toBeVisible();
  const reveal = root.getByRole('button',{name:'Reveal kana'});
  await expect(reveal).toBeEnabled();
  await reveal.focus();
  await page.keyboard.press('Enter');
  await expect(root.locator('.script-pair__glyph')).toHaveText('か');
});
