import { test,expect } from '@playwright/test';
const path='/learn/n5/module-01/chapter-01/lesson-07/';
test('keyboard input, local draft and recognition retry',async({page})=>{
 await page.goto(path);
 await expect(page.getByRole('heading',{name:/Write a first meeting/})).toBeVisible();
 const editor=page.getByLabel('Write two to five connected Japanese sentences');
 await editor.fill('私はエマです。学生です。');
 await page.getByRole('button',{name:'Save draft locally'}).click();
 await expect(page.getByText('Draft saved only on this device.')).toBeVisible();
 await editor.fill('');
 await page.getByRole('button',{name:'Load saved draft'}).click();
 await expect(editor).toHaveValue('私はエマです。学生です。');
 await page.getByRole('button',{name:'Clear draft'}).click();
 await expect(editor).toHaveValue('');
 const questions=page.locator('[data-question-id]');
 await expect(questions).toHaveCount(8);
 await questions.first().locator('input[type=radio]').first().focus();
 await page.keyboard.press('ArrowDown');
 await expect(questions.first().locator('input[type=radio]:checked')).toHaveCount(1);
 for(let i=0;i<8;i++) await questions.nth(i).locator('input[type=radio]').first().check();
 await page.getByRole('button',{name:'Check 8 answers'}).click();
 await expect(page.getByText(/Written recognition score:/)).toBeVisible();
 await page.getByRole('button',{name:'Retry questions'}).click();
 await expect(page.getByRole('button',{name:'Check 8 answers'})).toBeDisabled();
});
test('320px dark mode is usable without horizontal overflow',async({page})=>{
 await page.setViewportSize({width:320,height:720});await page.emulateMedia({colorScheme:'dark'});await page.goto(path);
 await expect(page.locator('[data-question-id]')).toHaveCount(8);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth)).toBe(false);
});